// Retrieval evaluation (C1-7): recall@5 and MRR for BM25, vector and hybrid over
// kb/eval/questions.jsonl (gold chunks = chunks containing a verbatim anchor).
//   node scripts/eval_retrieval.ts [--write]     --write refreshes kb/eval/RESULTS.md
// Query vectors are Ollama nomic-embed-text (kb/eval/query_vectors.json), so this
// runs offline; the web app's runtime embedder is the transformers.js build of the
// same model, so treat vector and hybrid numbers as close, not identical.
import { readFileSync, writeFileSync } from "node:fs";
import type { Chunk } from "../src/lib/un/kb.ts";
import { searchChunks } from "../src/lib/un/kb.ts";
import { hybridSearch, parseVectors, vectorRanking } from "../src/lib/un/vector.ts";

interface Q { id: string; area: string; question: string; gold: string[] }
export interface Row { method: string; recall5: number; mrr: number }

export interface Opts { dir?: string; set?: "tune" | "heldout"; perSource?: number; stem?: boolean; lexicalWeight?: number; skipExcerpts?: boolean }

const norm = (s: string) => s.toLowerCase().split(/\s+/).join(" ");

export function evaluate(o: Opts = {}): { rows: Row[]; n: number; chunks: number } {
  const dir = o.dir ?? "kb";
  const chunks = JSON.parse(readFileSync(`${dir}/chunks.json`, "utf8")) as Chunk[];
  const vectors = parseVectors(JSON.parse(readFileSync(`${dir}/vectors.json`, "utf8")), chunks);
  if (!vectors) throw new Error(`${dir}/vectors.json does not match ${dir}/chunks.json`);
  // Gold is recomputed from each question's verbatim anchor, so any chunking can be scored.
  const file = o.set === "heldout" ? "kb/eval/heldout.jsonl" : "kb/eval/questions.jsonl";
  const qs = readFileSync(file, "utf8").trim().split("\n").map((l) => {
    const q = JSON.parse(l) as Q & { anchor: string };
    return { ...q, gold: chunks.filter((c) => norm(c.text).includes(norm(q.anchor))).map((c) => c.chunk_id) };
  }).filter((q) => q.gold.length > 0 && !(o.skipExcerpts && q.gold.every((id) => id.includes("-excerpts#"))));
  const cap = { ...(o.perSource ? { perSource: o.perSource } : {}), ...(o.stem ? { stem: true } : {}), ...(o.lexicalWeight ? { lexicalWeight: o.lexicalWeight } : {}) };
  const qv = (JSON.parse(readFileSync("kb/eval/query_vectors.json", "utf8")) as { vectors: Record<string, number[]> }).vectors;
  const rankers: Record<string, (q: Q) => string[]> = {
    bm25: (q) => searchChunks(chunks, q.question, { k: 50, ...cap }).map((h) => h.chunk.chunk_id),
    vector: (q) => vectorRanking(chunks, vectors, qv[q.id], 50).map((v) => v.id),
    hybrid: (q) => hybridSearch(chunks, vectors, qv[q.id], q.question, { k: 50, ...cap }).hits.map((h) => h.chunk.chunk_id),
  };
  const rows = Object.entries(rankers).map(([method, rank]) => {
    let hit5 = 0, rr = 0;
    for (const q of qs) {
      const r = rank(q);
      const at = r.findIndex((id) => q.gold.includes(id));
      if (at >= 0 && at < 5) hit5++;
      if (at >= 0) rr += 1 / (at + 1);
    }
    return { method, recall5: hit5 / qs.length, mrr: rr / qs.length };
  });
  return { rows, n: qs.length, chunks: chunks.length };
}

function noteFor(rows: Row[]): string {
  const r = Object.fromEntries(rows.map((x) => [x.method, x]));
  const cmp = r.hybrid.recall5 > r.bm25.recall5 ? "Fusion raises recall@5 over BM25" : r.hybrid.recall5 === r.bm25.recall5 ? "Fusion does not change recall@5 relative to BM25" : "Fusion lowers recall@5 relative to BM25";
  const mrr = r.hybrid.mrr < r.bm25.mrr ? " and lowers MRR (the vector ranking pushes the exact chunk down)" : "";
  return `${cmp}${mrr}. Whether chunk size, a per-source cap, stemming, document prefixes or fusion weights help is recorded in kb/eval/EXPERIMENTS.md; none was tuned on these questions beyond the grid listed there. Questions whose answer is a short excerpt are easier to rank (the excerpt chunks are tiny); score only the others with --no-excerpts.`;
}

export const table = (rows: Row[]) =>
  ["| Method | recall@5 | MRR |", "|---|---|---|", ...rows.map((r) => `| ${r.method} | ${r.recall5.toFixed(2)} | ${r.mrr.toFixed(3)} |`)].join("\n");

if (process.argv[1]?.endsWith("eval_retrieval.ts")) {
  const arg = (name: string) => { const i = process.argv.indexOf(name); return i >= 0 ? process.argv[i + 1] : undefined; };
  const { rows, n, chunks } = evaluate({ dir: arg("--dir"), set: arg("--set") === "heldout" ? "heldout" : "tune", perSource: arg("--cap") ? Number(arg("--cap")) : undefined, stem: process.argv.includes("--stem"), lexicalWeight: arg("--lex") ? Number(arg("--lex")) : undefined, skipExcerpts: process.argv.includes("--no-excerpts") });
  const md = `# Retrieval evaluation (C1-7)\n\n${n} questions, ${chunks} chunks. Gold = chunks containing a verbatim anchor phrase from the source (kb/eval/make_questions.py), chosen from the text, not from rankings. Generated by \`node scripts/eval_retrieval.ts --write\`.\n\n${table(rows)}\n\nTarget from the plan: hybrid recall@5 of at least 0.85 (${rows.find((r) => r.method === "hybrid")!.recall5 >= 0.85 ? "met" : "NOT met"}).

Notes: ${noteFor(rows)}
`;
  console.log(md);
  if (process.argv.includes("--write")) writeFileSync("kb/eval/RESULTS.md", md);
}
