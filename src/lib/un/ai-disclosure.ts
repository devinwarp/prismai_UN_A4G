export const AI_DISCLOSURE_GATE = "ai_disclosure";
export const AI_OUTPUT_NOTICE = "Generated by an AI assistant.";
export const AI_OUTPUT_NOTICE_AR = "أُنشئ هذا المحتوى بواسطة مساعد ذكاء اصطناعي.";

/** Issued by Prism at the output boundary, independent of the prompt, audience or policy settings. */
export function discloseAiMessage(text: string, lang: "en" | "ar" = "en"): string {
  if (!text.trim()) return text;
  const notice = lang === "ar" ? AI_OUTPUT_NOTICE_AR : AI_OUTPUT_NOTICE;
  return text.startsWith(`${notice}\n\n`) || text === notice ? text : `${notice}\n\n${text}`;
}

/** Structured results carry their own provenance. Message fields keep it if copied out of the result. */
export function discloseAgentOutput(output: Record<string, unknown>): Record<string, unknown> {
  const disclosed = { ...output, ai_disclosure: AI_OUTPUT_NOTICE } as Record<string, unknown>;
  for (const key of ["email", "message", "acknowledgement", "notice"]) {
    const value = output[key];
    if (!value || typeof value !== "object") continue;
    const message = value as Record<string, unknown>;
    disclosed[key] = typeof message.body === "string" ? { ...message, body: discloseAiMessage(message.body) } : { ...message, ai_disclosure: AI_OUTPUT_NOTICE };
  }
  return disclosed;
}
